/* ============================================================================
   ESMERINGHOY — CATALOG STORE
   ----------------------------------------------------------------------------
   Sits between catalog.js and the pages. It lets the admin panel edit the
   catalog in the browser without a backend:

     catalog.js  ->  the published catalog (what visitors get)
     store.js    ->  if local edits exist, they SHADOW catalog.js for this
                     browser only, so you can preview your changes instantly

   Local edits are NOT live for visitors until you click "Publish live" in the
   admin panel, which writes the catalog to the deployed Worker's D1 database
   (or until you download the generated catalog.js and replace the file).

   API:
     EsmeringhoyStore.videos()          -> current working catalog
     EsmeringhoyStore.save(videos)      -> persist local edits
     EsmeringhoyStore.reset()           -> discard local edits
     EsmeringhoyStore.hasLocalEdits()   -> boolean
     EsmeringhoyStore.mediaBaseUrl()    -> Backblaze base URL in use
     EsmeringhoyStore.saveMediaBaseUrl(v)
     EsmeringhoyStore.exportCatalogJs() -> full catalog.js text, ready to save
     EsmeringhoyStore.slugify(text)     -> url-safe id fragment
   ========================================================================== */

(function () {
  var KEY = "esh_catalog_v2";

  var PUBLISHED_VIDEOS = (window.ESMERINGHOY_VIDEOS || []).slice();
  var PUBLISHED_CATEGORIES = (window.ESMERINGHOY_CATEGORIES || []).slice();
  var PUBLISHED_MEDIA = window.ESMERINGHOY_MEDIA || { b2BaseUrl: "", signEndpoint: "" };

  function readLocal() {
    try {
      var raw = localStorage.getItem(KEY);
      if (!raw) return null;
      var parsed = JSON.parse(raw);
      if (!parsed || !Array.isArray(parsed.videos)) return null;
      return parsed;
    } catch (e) {
      return null;
    }
  }

  /* Category nav follows whatever tags actually exist in the catalog. */
  function deriveCategories(videos) {
    var out = [];
    videos.forEach(function (v) {
      (v.tags || []).forEach(function (t) {
        if (t && out.indexOf(t) === -1) out.push(t);
      });
    });
    return out;
  }

  function apply(videos) {
    window.ESMERINGHOY_VIDEOS = videos;
    window.ESMERINGHOY_CATEGORIES = deriveCategories(videos);
  }

  function applyMedia(base, signEndpoint) {
    window.ESMERINGHOY_MEDIA = { b2BaseUrl: base || "", signEndpoint: signEndpoint || "" };
  }

  var localState = readLocal();
  if (localState) {
    apply(localState.videos);
    if (typeof localState.b2BaseUrl === "string") applyMedia(localState.b2BaseUrl, localState.signEndpoint);
  }

  function persist(videos, b2BaseUrl, signEndpoint) {
    localState = {
      videos: videos,
      b2BaseUrl: b2BaseUrl || "",
      signEndpoint: signEndpoint || "",
      savedAt: new Date().toISOString()
    };
    try {
      localStorage.setItem(KEY, JSON.stringify(localState));
    } catch (e) {
      console.warn("Could not persist catalog locally:", e);
    }
  }

  /* ---- catalog.js serialisation ---- */

  function js(value) {
    return JSON.stringify(value);
  }

  function serializeVideo(v) {
    var parts = [];
    parts.push("id: " + js(v.id));
    parts.push("title: " + js(v.title));
    parts.push("description: " + js(v.description || ""));
    parts.push("poster: " + (v.poster ? js(v.poster) : "null"));
    parts.push("video: " + (v.video ? js(v.video) : "null"));
    parts.push("duration: " + js(v.duration || "00:00"));
    parts.push("views: " + (Number(v.views) || 0));
    parts.push("rating: " + (Number(v.rating) || 0));
    parts.push("added: " + js(v.added || new Date().toISOString().slice(0, 10)));
    parts.push("tags: [" + (v.tags || []).map(js).join(", ") + "]");

    /* Extra parts and photos are edited as numbered rows; they must also
       survive a round trip through the panel. */
    if (v.clips && v.clips.length) {
      parts.push("clips: [" + v.clips.map(function (clip) {
        return "{ label: " + js(clip.label || "") + ", video: " + js(clip.video || "") + " }";
      }).join(", ") + "]");
    }
    if (v.gallery && v.gallery.length) {
      parts.push("gallery: [" + v.gallery.map(js).join(", ") + "]");
    }
    return "{ " + parts.join(", ") + " }";
  }

  var HEADER = [
    "/* ============================================================================",
    "   ESMERINGHOY — CONTENT CATALOG",
    "   ----------------------------------------------------------------------------",
    "   Generated by the admin panel. Replace this file to publish your catalog.",
    "   Schema: id, title, description, poster, video (direct media URL or Backblaze path),",
    "           clips[] (extra parts), gallery[] (photos), duration, views,",
    "           rating, added (ISO date), tags[]",
    "   ========================================================================== */",
    ""
  ];

  var api = {
    key: KEY,

    hasLocalEdits: function () {
      return !!localState;
    },

    videos: function () {
      return (window.ESMERINGHOY_VIDEOS || []).slice();
    },

    publishedVideos: function () {
      return PUBLISHED_VIDEOS.slice();
    },

    mediaBaseUrl: function () {
      return (window.ESMERINGHOY_MEDIA || {}).b2BaseUrl || "";
    },

    mediaSignEndpoint: function () {
      return (window.ESMERINGHOY_MEDIA || {}).signEndpoint || "";
    },

    save: function (videos) {
      persist(videos, api.mediaBaseUrl(), api.mediaSignEndpoint());
      apply(videos);
      return videos;
    },

    saveMediaBaseUrl: function (base) {
      persist(api.videos(), base, api.mediaSignEndpoint());
      applyMedia(base, api.mediaSignEndpoint());
      return base;
    },

    saveMediaSignEndpoint: function (endpoint) {
      persist(api.videos(), api.mediaBaseUrl(), endpoint);
      applyMedia(api.mediaBaseUrl(), endpoint);
      return endpoint;
    },

    reset: function () {
      localState = null;
      try {
        localStorage.removeItem(KEY);
      } catch (e) {}
      apply(PUBLISHED_VIDEOS.slice());
      applyMedia(PUBLISHED_MEDIA.b2BaseUrl || "", PUBLISHED_MEDIA.signEndpoint || "");
    },

    slugify: function (text) {
      return String(text || "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "")
        .slice(0, 48) || "clip";
    },

    exportCatalogJs: function () {
      var videos = (window.ESMERINGHOY_VIDEOS || []).slice();
      var lines = HEADER.slice();
      lines.push("/* Where media is loaded from, and how to sign those URLs. */");
      lines.push("window.ESMERINGHOY_MEDIA = {");
      lines.push("  /* Playback base: a public Backblaze URL, or your Cloudflare Worker. */");
      lines.push("  b2BaseUrl: " + js(api.mediaBaseUrl()) + ",");
      lines.push("  /* Set when the base needs signed URLs, e.g. https://media.example.com/token. */");
      lines.push("  signEndpoint: " + js(api.mediaSignEndpoint()));
      lines.push("};");
      lines.push("");
      lines.push("window.ESMERINGHOY_CATEGORIES = " + JSON.stringify(deriveCategories(videos), null, 2) + ";");
      lines.push("");
      lines.push("window.ESMERINGHOY_VIDEOS = [");
      videos.forEach(function (v) { lines.push("  " + serializeVideo(v) + ","); });
      lines.push("];");
      lines.push("");
      return lines.join("\n");
    }
  };

  window.EsmeringhoyStore = api;
})();
